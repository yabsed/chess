CREATE TABLE IF NOT EXISTS users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       TEXT NOT NULL UNIQUE,
    password_hash  TEXT NOT NULL,
    avatar         BYTEA,
    avatar_version TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL DEFAULT now() + interval '7 days'
);

-- Seats survive brief disconnects; expired games keep their result.
CREATE TABLE IF NOT EXISTS rooms (
    id         TEXT PRIMARY KEY,
    white_id   BIGINT NOT NULL REFERENCES users(id),
    black_id   BIGINT REFERENCES users(id),
    game       JSONB NOT NULL,
    finished   BOOLEAN NOT NULL DEFAULT false,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CHECK (white_id <> black_id)
);

-- Each user's current connection, room and matchmaking state.
CREATE TABLE IF NOT EXISTS players (
    user_id    BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    room_id    TEXT REFERENCES rooms(id) ON DELETE SET NULL,
    sid        TEXT UNIQUE,
    token_hash TEXT REFERENCES sessions(token_hash) ON DELETE SET NULL,
    seen_at    TIMESTAMPTZ,
    waiting_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS players_room ON players(room_id);
CREATE INDEX IF NOT EXISTS players_waiting ON players(waiting_at) WHERE waiting_at IS NOT NULL;

CREATE OR REPLACE VIEW online_players AS
    SELECT players.*
    FROM players
    JOIN sessions USING (token_hash)
    WHERE players.user_id = sessions.user_id
      AND players.sid IS NOT NULL
      AND players.seen_at > now() - interval '35 seconds'
      AND sessions.expires_at > now();

CREATE TABLE IF NOT EXISTS attempts (
    address    TEXT PRIMARY KEY,
    count      INTEGER NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);
